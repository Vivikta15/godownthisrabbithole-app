import { chromium } from 'playwright';
const BASE = 'http://127.0.0.1:8787';
const hits = [];
const isClarity = (u) => /clarity\.ms|c\.bing\.com/.test(u);
const since = (t) => hits.filter((h) => h.when >= t).length;
const check = (n, ok, ex = '') => console.log(`${ok ? 'PASS' : 'FAIL'} ${n}${ex ? ' (' + ex + ')' : ''}`);
const browser = await chromium.launch();
async function signupOnboarded(page) {
  await page.goto(BASE + '/', { waitUntil: 'networkidle' });
  await page.click("text=Let's wander");
  await page.fill('input[autocomplete="given-name"]', 'Test Person');
  await page.fill('input[type="email"]', `e2e${Date.now()}${Math.random()}@example.com`);
  await page.fill('input[type="password"]', 'testpass123');
  await page.click('text=Start my 3 free days');
  await page.waitForSelector("text=Let's get to know you", { timeout: 15000 });
  const cfg = await page.evaluate(async () => (await (await fetch('/api/config')).json()));
  await page.evaluate(async ({ cfg }) => { await fetch('/api/quiz', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ interestTags: [cfg.topics[0]], formats: [cfg.formats[0].id], length: 'medium', why: [], curious: '' }) }); }, { cfg });
  await page.goto(BASE + '/', { waitUntil: 'networkidle' });
}
const cfgRewrite = (region) => async (route) => {
  const u = route.request().url();
  if (isClarity(u)) { hits.push({ url: u, when: Date.now() }); return route.abort(); }
  if (u.endsWith('/api/config')) { const resp = await route.fetch(); const j = await resp.json(); j.consentRegion = region; return route.fulfill({ response: resp, json: j }); }
  return route.continue();
};
const ctx = await browser.newContext();
await ctx.route('**/*', cfgRewrite('strict'));
const page = await ctx.newPage();
let t = Date.now();
await signupOnboarded(page);
check('S1 config strict (rewritten)', (await page.evaluate(async () => (await (await fetch('/api/config')).json()).consentRegion)) === 'strict');
check('S2 config no-store', (await page.evaluate(async () => (await fetch('/api/config')).headers.get('cache-control'))) === 'no-store');
await page.waitForSelector('.consent', { timeout: 15000 });
check('S3 strict: banner shown, zero clarity before choice', since(t) === 0, `${since(t)}`);
await page.click('.consent >> text=No thanks');
t = Date.now();
await page.goto(BASE + '/', { waitUntil: 'networkidle' });
check('S4 explore: greeting masked', (await page.locator('.greet[data-clarity-mask="true"]').count()) >= 1);
check('S5 explore: detour masked', (await page.locator('.detour[data-clarity-mask="true"]').count()) >= 1);
await page.goto(BASE + '/?tab=trail', { waitUntil: 'networkidle' });
check('S6 trail: whole section masked', (await page.locator('section[data-clarity-mask="true"]').count()) >= 1);
check('S7 declined: zero clarity on eligible pages', since(t) === 0, `${since(t)}`);
await page.goto(BASE + '/', { waitUntil: 'networkidle' });
const startBtn = page.locator('text=Go down this rabbit hole');
if (await startBtn.count()) { await startBtn.click(); await page.waitForSelector('article.reading'); }
check('S8 reading article masked', (await page.locator('article.reading[data-clarity-mask="true"]').count()) >= 1);
check('S9 story body masked', (await page.locator('.story[data-clarity-mask="true"]').count()) >= 1);
await page.evaluate(() => localStorage.setItem('clarity-consent', 'yes'));
t = Date.now();
await page.goto(BASE + '/?reset=FROZENTOKEN999', { waitUntil: 'networkidle' });
await page.waitForTimeout(3000);
check('S10 token load: gate frozen closed after URL strip', since(t) === 0, `${since(t)}`);
await page.goto(BASE + '/', { waitUntil: 'networkidle' });
await page.waitForTimeout(1500);
const q = await page.evaluate(() => (window.clarity && window.clarity.q) ? window.clarity.q.map((a) => a[0] === 'consentv2' ? a[1] : a[0]) : null);
check('S11 tag injected after explicit yes', q !== null);
check('S12 ad storage always denied', Array.isArray(q) && q.some((x) => x && x.ad_Storage === 'denied' && x.analytics_Storage === 'granted'));
const p1 = await ctx.newPage();
await p1.goto(BASE + '/', { waitUntil: 'networkidle' });
await p1.waitForTimeout(1200);
const p2 = await ctx.newPage();
await p2.goto(BASE + '/?you=1', { waitUntil: 'networkidle' });
try { await p2.waitForSelector('text=Analytics are on', { timeout: 12000 }); }
catch { console.log('DBG p2 url', p2.url()); console.log('DBG p2 h1', await p2.locator('main h1').first().textContent().catch(() => 'none')); console.log('DBG p2 toggle texts', await p2.locator('button.ghost').allTextContents().catch(() => [])); }
const navPromise = p1.waitForEvent('framenavigated', { timeout: 12000 }).catch(() => null);
await p2.click('text=Analytics are on. Turn off');
const nav = await navPromise;
check('S13 cross-tab opt-out reloads collecting tab', !!nav);
t = Date.now();
await p1.waitForTimeout(2000);
check('S14 after cross-tab opt-out: zero clarity from old tab', since(t) === 0, `${since(t)}`);
await ctx.close();
const ctx2 = await browser.newContext();
await ctx2.route('**/*', cfgRewrite('open'));
const op = await ctx2.newPage();
t = Date.now();
await signupOnboarded(op);
await op.waitForTimeout(2000);
check('O1 open: no consent banner', (await op.locator('.consent').count()) === 0);
check('O2 open: default-on tag attempted (aborted)', since(t) >= 1, `${since(t)} attempted`);
await op.goto(BASE + '/?you=1', { waitUntil: 'networkidle' });
await op.waitForSelector('text=Analytics are on', { timeout: 15000 });
await op.click('text=Analytics are on. Turn off');
t = Date.now();
await op.goto(BASE + '/', { waitUntil: 'networkidle' });
await op.waitForTimeout(2000);
check('O3 open: opt-out stops collection', since(t) === 0, `${since(t)}`);
await ctx2.close();
await browser.close();
console.log('E2E_DONE');
